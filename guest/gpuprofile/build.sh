#!/usr/bin/env bash
# Builds Avo's GPU layers with the Android NDK (no Gradle) and writes them into
# the daemon as Base64 (host/AvoKit/Sources/AvoDaemonCore/GPUProfileHelper.swift):
#
#   libGLES_avo_profile.so  a GLES layer: reports the device profile's GPU in
#     an app's own glGetString (vendor, renderer, version) instead of ANGLE.
#   libVkLayer_avo_profile.so  VK_LAYER_AVO_profile: reports the device
#     profile's GPU in an app's own vkGetPhysicalDeviceProperties(2).
#
# HostAgent installs them in /data/local/debug/{gles,vulkan} when Android's
# copies differ; a device profile with a GPU turns them on
# (debug.gles.layers, debug.vulkan.layers).
#
#   ANDROID_HOME=~/Library/Android/sdk ./build.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
NDK="${ANDROID_NDK_HOME:-$SDK/ndk/$(ls "$SDK/ndk" | sort -V | tail -1)}"
BIN="$NDK/toolchains/llvm/prebuilt/$(ls "$NDK/toolchains/llvm/prebuilt" | head -1)/bin"
# Android 11 is the oldest Avo boots; the layers only use libc (and libdl).
CC="$BIN/aarch64-linux-android30-clang"
OUT="$HERE/build"
rm -rf "$OUT"
mkdir -p "$OUT"

# No build ID and no paths: the same sources and NDK give the same bytes, so
# the daemon replaces Android's copies only when something changed.
# 16 KiB pages work on 4 KiB and 16 KiB kernels.
FLAGS=(-std=c11 -O2 -fPIC -shared -fvisibility=hidden -Wall -Wextra -Werror
       -ffile-prefix-map="$HERE"=. -Wl,--build-id=none -Wl,-z,max-page-size=16384 -Wl,--no-undefined)
(cd "$HERE" && "$CC" "${FLAGS[@]}" -o "$OUT/libGLES_avo_profile.so" src/gles_layer.c -ldl)
(cd "$HERE" && "$CC" "${FLAGS[@]}" -o "$OUT/libVkLayer_avo_profile.so" src/vk_layer.c -ldl)
"$BIN/llvm-strip" --strip-unneeded "$OUT/libGLES_avo_profile.so" "$OUT/libVkLayer_avo_profile.so"

SWIFT="$ROOT/host/AvoKit/Sources/AvoDaemonCore/GPUProfileHelper.swift"
{
  echo "// Generated by guest/gpuprofile/build.sh from guest/gpuprofile/src. Do not edit."
  echo
  echo "/// Avo's GPU layers, which HostAgent installs in /data/local/debug (GuestGPUProfile)."
  echo "enum GPUProfileHelper {"
  echo "    /// libGLES_avo_profile.so"
  echo "    static let gles = \"$(base64 < "$OUT/libGLES_avo_profile.so" | tr -d '\n')\""
  echo "    /// libVkLayer_avo_profile.so"
  echo "    static let vulkan = \"$(base64 < "$OUT/libVkLayer_avo_profile.so" | tr -d '\n')\""
  echo "}"
} > "$SWIFT"
echo "built $(wc -c < "$OUT/libGLES_avo_profile.so" | tr -d ' ') + $(wc -c < "$OUT/libVkLayer_avo_profile.so" | tr -d ' ') bytes -> $SWIFT"
