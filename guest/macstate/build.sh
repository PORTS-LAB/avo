#!/usr/bin/env bash
# Builds avo-macstate.jar (a dex jar run with app_process: Android's system
# languages and shared audio focus, which have no shell command) and writes it into the daemon as
# Base64 (host/AvoKit/Sources/AvoDaemonCore/MacStateHelper.swift).
#
#   ANDROID_HOME=~/Library/Android/sdk ./build.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
API=36
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
JAR="$SDK/platforms/android-$API/android.jar"
OUT="$(mktemp -d)"
trap 'rm -rf "$OUT"' EXIT
mkdir -p "$OUT"/{classes,dex}

javac --release 17 -nowarn -cp "$JAR" -d "$OUT/classes" $(find "$HERE/src" -name '*.java')
"$BT/d8" --release --min-api 30 --lib "$JAR" --output "$OUT/dex" $(find "$OUT/classes" -name '*.class')
(cd "$OUT/dex" && zip -q -X "$OUT/avo-macstate.jar" classes.dex)

SWIFT="$ROOT/host/AvoKit/Sources/AvoDaemonCore/MacStateHelper.swift"
{
  echo "// Generated by guest/macstate/build.sh from guest/macstate/src. Do not edit."
  echo
  echo "/// avo-macstate.jar: Android's system languages and shared audio focus, which HostAgent sets with app_process."
  echo "enum MacStateHelper {"
  echo "    static let jar = \"$(base64 < "$OUT/avo-macstate.jar" | tr -d '\n')\""
  echo "}"
} > "$SWIFT"
echo "built avo-macstate.jar ($(wc -c < "$OUT/avo-macstate.jar" | tr -d ' ') bytes) -> $SWIFT"
