#!/usr/bin/env bash
# Builds avo-fingerprint.jar (a dex jar run with app_process: Android's
# enrolled fingerprints, which have no shell command to list, rename or
# remove them) and writes it into the daemon as Base64
# (host/AvoKit/Sources/AvoDaemonCore/FingerprintHelper.swift).
#
#   ANDROID_HOME=~/Library/Android/sdk ./build.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
API=36
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
JAR="$SDK/platforms/android-$API/android.jar"
OUT="$(mktemp -d)"
trap 'rm -rf "$OUT"' EXIT
mkdir -p "$OUT"/{classes,dex}

javac --release 17 -nowarn -cp "$JAR" -d "$OUT/classes" $(find "$HERE/src" -name '*.java')
"$BT/d8" --release --min-api 30 --lib "$JAR" --output "$OUT/dex" $(find "$OUT/classes" -name '*.class')
(cd "$OUT/dex" && zip -q -X "$OUT/avo-fingerprint.jar" classes.dex)

SWIFT="$ROOT/host/AvoKit/Sources/AvoDaemonCore/FingerprintHelper.swift"
{
  echo "// Generated by guest/fingerprint/build.sh from guest/fingerprint/src. Do not edit."
  echo
  echo "/// avo-fingerprint.jar: Android's enrolled fingerprints, which HostAgent lists, names and removes with app_process."
  echo "enum FingerprintHelper {"
  echo "    static let jar = \"$(base64 < "$OUT/avo-fingerprint.jar" | tr -d '\n')\""
  echo "}"
} > "$SWIFT"
echo "built avo-fingerprint.jar ($(wc -c < "$OUT/avo-fingerprint.jar" | tr -d ' ') bytes) -> $SWIFT"
